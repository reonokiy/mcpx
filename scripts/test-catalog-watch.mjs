import assert from "node:assert/strict";
import { CatalogSource } from "../web/catalog.js";
import { WorkerCatalog } from "../web/worker-catalog.js";

const source = new CatalogSource();
const first = source.subscribe(), second = source.subscribe();
assert.equal(first.tryNext(), undefined);
const controller = new AbortController();
const waiting = first.next({signal:controller.signal});
await assert.rejects(first.next(), {code:"Busy"});
assert.throws(()=>first.tryNext(), {code:"Busy"});
controller.abort(); await assert.rejects(waiting, {code:"Cancelled"});
for (let i=0;i<100_000;i++) source.change({published:true});
source.change({invalidated:true});
assert.deepEqual(first.tryNext(), {done:false, value:{published:true, invalidated:true}});
assert.equal(first.tryNext(), undefined);
source.close();
assert.deepEqual(await second.next(), {done:false, value:{published:true, invalidated:true}});
assert.deepEqual(await second.next(), {done:true, value:undefined});
assert.throws(()=>source.subscribe(), {code:"TransportClosed"});
assert.equal(source.watchers.size, 0);
const bounded = new CatalogSource(), watches = Array.from({length:64},()=>bounded.subscribe());
assert.throws(()=>bounded.subscribe(), {code:"LimitExceeded"});
const pending = watches[0].next();
await watches[0].return(); assert.equal((await pending).done, true);
const replacement = bounded.subscribe();
assert.equal(bounded.watchers.size,64);
const closed = replacement.next(); bounded.close(); assert.equal((await closed).done,true);
console.log("PASS catalog subscriptions: coalescing, independent readers, 64 slots, one waiter, abort/return/close");

const frames = [], channel = new WorkerCatalog(frame=>frames.push(frame));
channel.change({published:true});
for (let i=0;i<100_000;i++) channel.change({published:true, invalidated:i%2===0});
assert.equal(frames.length,1);
assert.deepEqual(channel.pending,{published:true, invalidated:true});
channel.acknowledge(2); assert.equal(frames.length,1);
channel.acknowledge(1); assert.equal(frames.length,2);
assert.equal(frames[1].invalidated,true);
channel.change({invalidated:true});
channel.acknowledge(1); assert.equal(frames.length,2);
assert.deepEqual(channel.close(),{id:3,published:false,invalidated:true});
channel.acknowledge(2); channel.change({published:true}); assert.equal(frames.length,2);
assert.equal(channel.close(),undefined);
const exhausted = new WorkerCatalog(()=>{}); exhausted.next=Number.MAX_SAFE_INTEGER;
exhausted.change({published:true}); exhausted.change({invalidated:true});
assert.throws(()=>exhausted.acknowledge(Number.MAX_SAFE_INTEGER), {code:"LimitExceeded"});
console.log("PASS worker catalog channel: bounded unacknowledged state, exact ACKs, final cell, ID exhaustion");
